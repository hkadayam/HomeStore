// ── Comparators ───────────────────────────────────────────────────────────────

template < typename T >
struct compare_val {
    bool operator()(const T& lhs, const T& rhs, Operator oper) {
        switch (oper) {
        case Operator::DONT_CARE:
            return true;
        case Operator::EQUAL:
            return lhs == rhs;
        case Operator::NOT_EQUAL:
            return lhs != rhs;
        case Operator::GREATER_THAN:
            return lhs > rhs;
        case Operator::LESS_THAN:
            return lhs < rhs;
        case Operator::GREATER_THAN_OR_EQUAL:
            return lhs >= rhs;
        case Operator::LESS_THAN_OR_EQUAL:
            return lhs <= rhs;
        default:
            return false;
        }
    }
};

template <>
struct compare_val< std::string > {
    bool operator()(const std::string& lhs, const std::string& rhs, Operator oper) {
        switch (oper) {
        case Operator::DONT_CARE:
            return true;
        case Operator::EQUAL:
            return lhs == rhs;
        case Operator::NOT_EQUAL:
            return lhs != rhs;
        case Operator::GREATER_THAN:
            return lhs > rhs;
        case Operator::LESS_THAN:
            return lhs < rhs;
        case Operator::GREATER_THAN_OR_EQUAL:
            return lhs >= rhs;
        case Operator::LESS_THAN_OR_EQUAL:
            return lhs <= rhs;
        case Operator::REG_EX: {
            const std::regex re(rhs);
            return std::sregex_iterator(lhs.begin(), lhs.end(), re) != std::sregex_iterator();
        }
        default:
            return false;
        }
    }
};

template <>
struct compare_val< const char* > {
    bool operator()(const char* lhs, const char* rhs, Operator oper) {
        switch (oper) {
        case Operator::DONT_CARE:
            return true;
        case Operator::EQUAL:
            return (lhs && rhs && std::strcmp(lhs, rhs) == 0) || (!lhs && !rhs);
        case Operator::NOT_EQUAL:
            return !((lhs && rhs && std::strcmp(lhs, rhs) == 0) || (!lhs && !rhs));
        case Operator::GREATER_THAN:
            return lhs && rhs ? std::strcmp(lhs, rhs) > 0 : (lhs && !rhs);
        case Operator::LESS_THAN:
            return lhs && rhs ? std::strcmp(lhs, rhs) < 0 : (!lhs && rhs);
        case Operator::GREATER_THAN_OR_EQUAL:
            return lhs && rhs ? std::strcmp(lhs, rhs) >= 0 : !rhs;
        case Operator::LESS_THAN_OR_EQUAL:
            return lhs && rhs ? std::strcmp(lhs, rhs) <= 0 : !lhs;
        case Operator::REG_EX: {
            if (!lhs || !rhs) { return false; }
            const std::regex re(rhs);
            const std::string s(lhs);
            return std::sregex_iterator(s.begin(), s.end(), re) != std::sregex_iterator();
        }
        default:
            return false;
        }
    }
};

// ── FlipTimerBase — interface ─────────────────────────────────────────────────
